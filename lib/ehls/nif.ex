defmodule EHLS.NIF do
  @moduledoc """
  A `defhls` function as a NIF: its C, built into the runtime and run on the CPU as machine code, outside the VM,
  instead of as a circuit or as Elixir in the VM (`cpu: :nif`; NIF: a Native Implemented Function, as Erlang calls a
  function the VM calls but does not run itself). The C is checked on the host before it becomes one.

  `EHLS.MLIR`'s output (`func` / `arith` / `cf` / `memref`) is written as C: every SSA value is a
  `uint64_t` holding its value cut to its width (zero-extended), so an `iN` of up to 64 bits needs no
  more. The kernel then gets a batch function on the packed format of `EHLS.packed_size/1`
  (each scalar in 1, 2, 4 or 8 bytes, little-endian, a tuple left to right), so a binary from
  the FPGA's CPU end is read in place, with nothing converted:

      typedef struct { uint64_t s[..]; uint32_t mem[..]; } <kernel>_t;   // the state and the memory space
      void   <kernel>_init(<kernel>_t *st);                              // the initial state
      size_t <kernel>_run(<kernel>_t *st, const uint8_t *in, size_t n,  // n elements in, bytes out
                          uint8_t *out, const uint64_t *levels);

  `mix ehls.compile --target cpu` writes the C and checks it: each kernel is built with the host's
  C compiler and run on the vectors of `mix ehls.compile` (edge values, random ones, a stream from
  the initial state restarted halfway, here also in chunks of 1, 3 and 7 elements, so that the state
  is kept between calls), against the same function run by Elixir. Needs `gcc` (or `cc`), no CIRCT.
  """

  import Bitwise

  @doc """
  The C source of a kernel: `mlir` is its `<kernel>.mlir`, `sig` the decoded `<kernel>.sig`. With
  `test: true` it ends with a `main` (`EHLS_TEST`) that the check runs.
  """
  def c_source(mlir, sig, opts \\ []) when is_binary(mlir) and is_map(sig) do
    k = sig["kernel"]
    f = parse(mlir)
    ins = flat_types(sig["arg"])
    outs = flat_types(sig["ret"])
    state = Enum.map(sig["state"], &type!/1)
    levels = sig["args"]
    emit? = sig["emit"] == true
    {mem_arg, scalars} = Enum.split_with(f.args, fn {_, t} -> match?({:memref, _}, t) end)

    if length(scalars) != length(ins) + length(state) + length(levels),
      do: raise(ArgumentError, "#{k}: #{length(scalars)} scalar arguments, the signature says #{length(ins) + length(state) + length(levels)}")

    nres = (if emit?, do: 1, else: 0) + length(outs) + length(state)
    if length(f.results) != nres and not (state == [] and length(f.results) == length(outs)),
      do: raise(ArgumentError, "#{k}: #{length(f.results)} results, expected #{nres}")

    [
      header(k),
      step(k, f, mem_arg),
      wrapper(k, sig, ins, outs, state, levels, emit?, mem_arg),
      if(opts[:test], do: harness(k, ins, outs, levels), else: "")
    ]
    |> IO.iodata_to_binary()
  end

  # ---- the MLIR text

  defp parse(text) do
    lines =
      text
      |> String.split("\n")
      |> Enum.map(&String.trim/1)
      |> Enum.reject(&(&1 in ["", "module {", "}"]))

    [head | body] = lines

    [_, name, args, results] =
      Regex.run(~r/^func\.func @(\w+)\((.*)\) -> \((.*)\) \{$/, head) ||
        raise ArgumentError, "unsupported function header: #{head}"

    args = for a <- split(args), do: (fn [n, t] -> {n, mtype(t)} end).(String.split(a, ": "))
    results = for r <- split(results), do: mtype(r)

    labels =
      for l <- body, [_, label, params] <- [Regex.run(~r/^\^(\w+)(?:\((.*)\))?:$/, l)], into: %{} do
        {label, for(p <- split(params), do: p |> String.split(": ") |> hd())}
      end

    %{name: name, args: args, results: results, body: body, labels: labels}
  end

  defp split(nil), do: []
  defp split(""), do: []
  defp split(s), do: String.split(s, ", ")

  defp mtype("index"), do: 64
  defp mtype("i" <> n) do
    w = String.to_integer(n)
    if w > 64, do: raise(ArgumentError, "the MLIR has an i#{w}: the CPU target holds a value in 64 bits")
    w
  end

  defp mtype("memref<" <> rest) do
    [size, _] = String.split(rest, "x")
    {:memref, String.to_integer(size)}
  end

  defp v("%" <> n), do: String.replace(n, ~r/\W/, "_")

  defp mask(64), do: 0xFFFFFFFFFFFFFFFF
  defp mask(w), do: (1 <<< w) - 1

  defp hex(n), do: "0x" <> String.upcase(Integer.to_string(n, 16)) <> "ULL"

  # ---- the kernel's step function

  defp header(k) do
    """
    /* #{k}: generated by `mix ehls.compile --target cpu` (EHLS.NIF). Do not edit. */
    #include <stddef.h>
    #include <stdint.h>

    static inline int64_t #{k}_sx(uint64_t x, int w) { return (int64_t)(x << (64 - w)) >> (64 - w); }

    """
  end

  defp step(k, f, mem_arg) do
    params =
      Enum.map(f.args, fn
        {n, {:memref, _}} -> "uint32_t *#{v(n)}"
        {n, _} -> "uint64_t #{v(n)}"
      end) ++ ["uint64_t *r"]

    arg_names = Enum.map(f.args, fn {n, _} -> v(n) end)

    defined =
      for l <- f.body, [_, name] <- [Regex.run(~r/^(%\w+) = /, l)], do: v(name)

    block_args = f.labels |> Map.values() |> List.flatten() |> Enum.map(&v/1)
    locals = Enum.uniq(defined ++ block_args) -- arg_names
    _ = mem_arg

    decl = if locals == [], do: "", else: "  uint64_t #{Enum.join(locals, ", ")};\n"
    code = Enum.map(f.body, &stmt(&1, k, f)) |> Enum.reject(&(&1 == ""))

    # an argument the body does not use (a state it only replaces, say) is not a warning
    unused = Enum.map_join(arg_names, "", &"  (void)#{&1};\n")
    "static void #{k}_step(#{Enum.join(params, ", ")}) {\n#{decl}#{unused}#{Enum.join(code, "\n")}\n}\n\n"
  end

  defp stmt(l, k, f) do
    cond do
      m = Regex.run(~r/^(%\w+) = arith\.constant (\S+)(?: : (\w+))?$/, l) ->
        [_, d, lit | t] = m

        {val, w} =
          case {lit, t} do
            {"true", _} -> {1, 1}
            {"false", _} -> {0, 1}
            {n, [ty]} -> {String.to_integer(n), mtype(ty)}
          end

        "  #{v(d)} = #{hex(val &&& mask(w))};"

      m = Regex.run(~r/^(%\w+) = arith\.(addi|subi|muli|andi|ori|xori|shli|shrui|shrsi) (%\w+), (%\w+) : (\w+)$/, l) ->
        [_, d, op, a, b, ty] = m
        [d, a, b, w] = [v(d), v(a), v(b), mtype(ty)]
        m = hex(mask(w))

        e =
          case op do
            "addi" -> "(#{a} + #{b}) & #{m}"
            "subi" -> "(#{a} - #{b}) & #{m}"
            "muli" -> "(#{a} * #{b}) & #{m}"
            "andi" -> "#{a} & #{b}"
            "ori" -> "#{a} | #{b}"
            "xori" -> "#{a} ^ #{b}"
            "shli" -> "#{b} < 64 ? (#{a} << #{b}) & #{m} : 0"
            "shrui" -> "#{b} < 64 ? #{a} >> #{b} : 0"
            "shrsi" -> "(uint64_t)(#{k}_sx(#{a}, #{w}) >> (#{b} < 63 ? #{b} : 63)) & #{m}"
          end

        "  #{d} = #{e};"

      m = Regex.run(~r/^(%\w+) = arith\.cmpi (\w+), (%\w+), (%\w+) : (\w+)$/, l) ->
        [_, d, pred, a, b, ty] = m
        w = mtype(ty)
        {x, y} = if String.starts_with?(pred, "s"), do: {"#{k}_sx(#{v(a)}, #{w})", "#{k}_sx(#{v(b)}, #{w})"}, else: {v(a), v(b)}

        op =
          case pred do
            "eq" -> "=="
            "ne" -> "!="
            p when p in ["ult", "slt"] -> "<"
            p when p in ["ule", "sle"] -> "<="
            p when p in ["ugt", "sgt"] -> ">"
            p when p in ["uge", "sge"] -> ">="
          end

        "  #{v(d)} = #{x} #{op} #{y};"

      m = Regex.run(~r/^(%\w+) = arith\.select (%\w+), (%\w+), (%\w+) : (\w+)$/, l) ->
        [_, d, c, a, b, _] = m
        "  #{v(d)} = #{v(c)} ? #{v(a)} : #{v(b)};"

      m = Regex.run(~r/^(%\w+) = arith\.(trunci|extui|extsi|index_cast) (%\w+) : (\w+) to (\w+)$/, l) ->
        [_, d, op, a, from, to] = m
        {from, to} = {mtype(from), mtype(to)}

        e =
          case op do
            "trunci" -> "#{v(a)} & #{hex(mask(to))}"
            "extsi" -> "(uint64_t)#{k}_sx(#{v(a)}, #{from}) & #{hex(mask(to))}"
            _ -> v(a)
          end

        "  #{v(d)} = #{e};"

      m = Regex.run(~r/^(%\w+) = memref\.load (%\w+)\[(%\w+)\] : memref<(\d+)x\w+>$/, l) ->
        [_, d, mem, i, size] = m
        "  #{v(d)} = #{v(mem)}[#{v(i)} & #{String.to_integer(size) - 1}];"

      m = Regex.run(~r/^memref\.store (%\w+), (%\w+)\[(%\w+)\] : memref<(\d+)x\w+>$/, l) ->
        [_, x, mem, i, size] = m
        "  #{v(mem)}[#{v(i)} & #{String.to_integer(size) - 1}] = (uint32_t)#{v(x)};"

      m = Regex.run(~r/^cf\.br \^(\w+)(?:\((.*) : .*\))?$/, l) ->
        [_, label | vals] = m
        vals = split(List.first(vals))
        params = Map.fetch!(f.labels, label)

        # the block's arguments are assigned together (one may be another's source)
        moves =
          vals
          |> Enum.with_index()
          |> Enum.map_join("", fn {x, j} -> " uint64_t t#{j} = #{v(x)};" end)

        sets = params |> Enum.with_index() |> Enum.map_join("", fn {p, j} -> " #{v(p)} = t#{j};" end)
        if vals == [], do: "  goto #{label};", else: "  {#{moves}#{sets} }\n  goto #{label};"

      m = Regex.run(~r/^cf\.cond_br (%\w+), \^(\w+), \^(\w+)$/, l) ->
        [_, c, a, b] = m
        "  if (#{v(c)}) goto #{a}; else goto #{b};"

      m = Regex.run(~r/^\^(\w+)(?:\(.*\))?:$/, l) ->
        "#{Enum.at(m, 1)}:;"

      m = Regex.run(~r/^return (.*) : .*$/, l) ->
        rs = m |> Enum.at(1) |> split()
        Enum.with_index(rs) |> Enum.map_join("\n", fn {x, i} -> "  r[#{i}] = #{v(x)};" end) |> Kernel.<>("\n  return;")

      l == "return" ->
        "  return;"

      true ->
        raise ArgumentError, "#{f.name}: unsupported MLIR: #{l}"
    end
  end

  # ---- the batch function on the packed format

  defp wrapper(k, sig, ins, outs, state, levels, emit?, mem_arg) do
    mem_size = with [{_, {:memref, n}}] <- mem_arg, do: n, else: (_ -> 0)
    in_bytes = ins |> Enum.map(&EHLS.packed_size/1) |> Enum.sum()
    out_bytes = outs |> Enum.map(&EHLS.packed_size/1) |> Enum.sum()
    e = if emit?, do: 1, else: 0

    init_state = for {w, i} <- Enum.with_index(sig["init"]), do: "  st->s[#{i}] = #{hex(w &&& 0xFFFFFFFF)};\n"
    roms = rom_init(sig["space"])

    reads =
      ins
      |> Enum.map_reduce(0, fn t, off -> {"    uint64_t a#{off} = #{k}_rd(p, #{EHLS.packed_size(t)}); p += #{EHLS.packed_size(t)};\n", off + 1} end)
      |> elem(0)

    call_args =
      Enum.map(0..(length(ins) - 1)//1, &"a#{&1}") ++
        Enum.map(0..(length(state) - 1)//1, &"st->s[#{&1}]") ++
        Enum.map(0..(length(levels) - 1)//1, &"lv[#{&1}]") ++
        if(mem_size > 0, do: ["st->mem"], else: [])

    writes =
      outs
      |> Enum.with_index()
      |> Enum.map_join("", fn {t, i} -> "      #{k}_wr(o, r[#{e + i}], #{EHLS.packed_size(t)}); o += #{EHLS.packed_size(t)};\n" end)

    next_state = Enum.map_join(0..(length(state) - 1)//1, "", &"    st->s[#{&1}] = r[#{e + length(outs) + &1}];\n")
    body_write = if emit?, do: "    if (r[0]) {\n#{writes}    }\n", else: writes

    """
    #define #{String.upcase(k)}_IN_BYTES #{in_bytes}
    #define #{String.upcase(k)}_OUT_BYTES #{out_bytes}
    #define #{String.upcase(k)}_LEVELS #{length(levels)}

    typedef struct { uint64_t s[#{max(length(state), 1)}]; uint32_t mem[#{max(mem_size, 1)}]; } #{k}_t;

    static inline uint64_t #{k}_rd(const uint8_t *p, int n) {
      uint64_t x = 0;
      for (int i = n - 1; i >= 0; i--) x = (x << 8) | p[i];
      return x;
    }

    static inline void #{k}_wr(uint8_t *p, uint64_t x, int n) {
      for (int i = 0; i < n; i++) p[i] = (uint8_t)(x >> (8 * i));
    }

    void #{k}_init(#{k}_t *st) {
      (void)st;
    #{init_state}#{if mem_size > 0, do: "  for (int i = 0; i < #{mem_size}; i++) st->mem[i] = 0;\n", else: ""}#{roms}}

    /* n elements from `in` (#{in_bytes} bytes each) through the kernel; the bytes written to `out` are returned
       (#{out_bytes} per element#{if emit?, do: ", fewer where the kernel skips", else: ""}); `lv`: the levels, as the circuit has them wired. */
    size_t #{k}_run(#{k}_t *st, const uint8_t *in, size_t n, uint8_t *out, const uint64_t *lv) {
      const uint8_t *p = in;
      uint8_t *o = out;
      (void)lv;
      (void)st;
      for (size_t i = 0; i < n; i++) {
        uint64_t r[#{length(outs) + length(state) + e + 1}];
    #{reads}    #{k}_step(#{Enum.join(call_args, ", ")}, r);
    #{next_state}#{body_write}  }
      return (size_t)(o - out);
    }

    """
  end

  defp rom_init(nil), do: ""

  defp rom_init(%{"regions" => regions}) do
    for %{"kind" => "rom", "base" => base, "values" => values} <- regions, {x, i} <- Enum.with_index(values) do
      "  st->mem[#{base + i}] = #{hex(x &&& 0xFFFFFFFF)};\n"
    end
    |> Enum.join()
  end

  # a main for the check: test_<kernel> in.bin out.bin chunk [level...]
  defp harness(k, ins, _outs, levels) do
    n = String.upcase(k)
    _ = ins

    """
    #ifdef EHLS_TEST
    #include <stdio.h>
    #include <stdlib.h>

    int main(int argc, char **argv) {
      if (argc < 4 + #{length(levels)}) return 2;
      FILE *f = fopen(argv[1], "rb");
      if (!f) return 2;
      fseek(f, 0, SEEK_END);
      long size = ftell(f);
      fseek(f, 0, SEEK_SET);
      uint8_t *in = malloc(size + 1);
      uint8_t *out = malloc(size / #{n}_IN_BYTES * #{n}_OUT_BYTES + 16);
      if (fread(in, 1, size, f) != (size_t)size) return 2;
      fclose(f);
      size_t chunk = strtoul(argv[3], 0, 10), count = size / #{n}_IN_BYTES, got = 0;
      uint64_t lv[#{max(length(levels), 1)}];
      for (int i = 0; i < #{length(levels)}; i++) lv[i] = (uint64_t)strtoll(argv[4 + i], 0, 10);
      static #{k}_t st;
      #{k}_init(&st);
      for (size_t at = 0; at < count; at += chunk) {
        size_t m = count - at < chunk ? count - at : chunk;
        got += #{k}_run(&st, in + at * #{n}_IN_BYTES, m, out + got, lv);
      }
      f = fopen(argv[2], "wb");
      fwrite(out, 1, got, f);
      fclose(f);
      return 0;
    }
    #endif
    """
  end

  # ---- the types of a signature ("u16", or a list of them, nested)

  defp type!("u" <> n), do: {String.to_integer(n), false}
  defp type!("s" <> n), do: {String.to_integer(n), true}

  defp flat_types(t) when is_binary(t), do: [type!(t)]
  defp flat_types(l) when is_list(l), do: Enum.flat_map(l, &flat_types/1)

  @doc false
  # the layout `EHLS.pack/2` takes for a signature's type
  def layout(t) when is_binary(t), do: EHLS.layout(type!(t))
  def layout(l) when is_list(l), do: l |> Enum.map(&layout/1) |> List.to_tuple()

  # ---- the kernels together: what a runtime backend builds in

  @doc """
  The kernels of `<dir>/*.sig` as one C file (their sources and the table `ehls_nif_kernels` of
  priv/backend/atomvm/src/ehls_nif.h) and the Erlang module `hw_nif` that numbers them
  (`kernel/1`) and gives their layouts (`layouts/1`, for `pack` / `unpack`). `{c, erl}`.
  """
  def registry(dir) do
    sigs =
      dir
      |> Path.join("*.sig")
      |> Path.wildcard()
      |> Enum.map(&(&1 |> File.read!() |> JSON.decode!()))
      |> Enum.sort_by(&name/1)

    sources = for sig <- sigs, do: c_source(File.read!(Path.join(dir, sig["kernel"] <> ".mlir")), sig)

    rows =
      for sig <- sigs do
        k = sig["kernel"]
        n = String.upcase(k)

        "  { \"#{name(sig)}\", #{n}_IN_BYTES, #{n}_OUT_BYTES, #{n}_LEVELS, #{length(sig["state"])}, sizeof(#{k}_t), #{if sig["emit"], do: 1, else: 0}, #{k}_init_v, #{k}_run_v },\n"
      end

    wrappers =
      for sig <- sigs do
        k = sig["kernel"]

        "static void #{k}_init_v(void *st) { #{k}_init((#{k}_t *)st); }\n" <>
          "static size_t #{k}_run_v(void *st, const uint8_t *in, size_t n, uint8_t *out, const uint64_t *lv) { return #{k}_run((#{k}_t *)st, in, n, out, lv); }\n"
      end

    c =
      IO.iodata_to_binary([
        "/* Generated by `mix ehls.compile --target cpu` (EHLS.NIF.registry/1). Do not edit. */\n",
        sources,
        # included by ehls_nif.c, which has the header already (it need not be on the include path)
        "#ifndef EHLS_NIF_H\n#include \"ehls_nif.h\"\n#endif\n\n",
        wrappers,
        "\nconst struct ehls_nif_kernel ehls_nif_kernels[] = {\n",
        rows,
        "  { 0 }\n};\nconst int ehls_nif_count = #{length(sigs)};\n"
      ])

    kernels = for {sig, i} <- Enum.with_index(sigs), do: "kernel('#{name(sig)}') -> #{i};\n"
    layouts = for sig <- sigs, do: "layouts('#{name(sig)}') -> {#{inspect(layout(sig["arg"]))}, #{inspect(layout(sig["ret"]))}};\n"

    erl =
      IO.iodata_to_binary([
        "%% Generated by `mix ehls.compile --target cpu` (EHLS.NIF.registry/1): the numbers of the NIF kernels.\n",
        "-module(hw_nif).\n-export([kernel/1, layouts/1]).\n\n",
        kernels,
        "kernel(K) -> erlang:error({no_nif_kernel, K}).\n\n",
        layouts,
        "layouts(K) -> erlang:error({no_nif_kernel, K}).\n"
      ])

    {c, erl}
  end

  defp name(sig), do: sig["module"] <> "." <> sig["function"]

  # ---- the check

  @doc """
  Writes the C of every kernel of `<dir>/*.sig` (with its `.mlir`) as `<dir>/<kernel>.c`, builds it with the
  host's C compiler and compares it with the Elixir function, which must be loaded. Returns
  `[{kernel, vectors, errors}]`. `n` random vectors per kernel.
  """
  def check(dir, n \\ 2000) do
    cc = System.find_executable("gcc") || System.find_executable("cc") || raise "no C compiler (gcc) found"

    for sigf <- dir |> Path.join("*.sig") |> Path.wildcard() |> Enum.sort() do
      sig = sigf |> File.read!() |> JSON.decode!()
      k = sig["kernel"]
      c = Path.join(dir, k <> ".c")
      File.write!(c, c_source(File.read!(Path.join(dir, k <> ".mlir")), sig, test: true))
      exe = Path.join(dir, "test_" <> k)

      case System.cmd(cc, ["-O2", "-Wall", "-Wno-unused-variable", "-Wno-unused-label", "-Wno-unused-but-set-variable", "-DEHLS_TEST", "-o", exe, c], stderr_to_stdout: true) do
        {_, 0} -> :ok
        {out, _} -> raise "#{k}: the C compiler failed:\n#{out}"
      end

      {vectors, errors} = run_vectors(sig, exe, dir, n)
      {k, vectors, errors}
    end
  end

  @edge [0, 1, 0x7FFF, 0x8000, 0xFFFF, 0x10000, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x80008000, 0x7FFF7FFF]
  @edge64 [0x100000000, 0x7FFFFFFFFFFF, 0x800000000000, 0xFFFFFFFFFFFF, 0x7FFFFFFFFFFFFFFF, 0x8000000000000000, 0xFFFFFFFFFFFFFFFF]

  defp run_vectors(sig, exe, dir, n) do
    mod = Module.concat([sig["module"]])
    fun = String.to_atom(sig["function"])
    in_layout = layout(sig["arg"])
    out_layout = layout(sig["ret"])
    ins = flat_types(sig["arg"])
    levels = for a <- sig["args"], do: a["default"]
    stateful? = sig["state"] != [] and not sig["pure"]
    :rand.seed(:exsss, {1, 2, 3})

    edge = @edge ++ if(sig["lane"] > 32, do: @edge64, else: [])
    rnd = fn {w, _} -> :rand.uniform(1 <<< w) - 1 end
    ni = length(ins)

    flat =
      if ni == 1 do
        [t] = ins
        for(e <- edge, do: [e]) ++ for(_ <- 1..n//1, do: [rnd.(t)])
      else
        at = for p <- 0..(ni - 1), e <- edge, do: (for {t, i} <- Enum.with_index(ins), do: if(i == p, do: e, else: rnd.(t)))
        at ++ for(_ <- 1..n//1, do: Enum.map(ins, rnd))
      end

    xs = for words <- flat, do: shape(sig["arg"], Enum.zip(ins, words) |> Enum.map(fn {{w, s}, x} -> EHLS.wrap(x, w, s) end)) |> elem(0)
    {a, b} = Enum.split(xs, div(length(xs), 2))

    errors =
      for {part, idx} <- Enum.with_index(if(stateful?, do: [a, b], else: [xs])), reduce: [] do
        errs ->
          expected =
            if stateful? do
              Enum.reduce(part, {apply(mod, fun, [:zero]), []}, fn x, {st, acc} ->
                case apply(mod, fun, [x, st | levels]) do
                  {[], st} -> {st, acc}
                  {[y], st} -> {st, [EHLS.pack([y], out_layout) | acc]}
                  {y, st} -> {st, [EHLS.pack([y], out_layout) | acc]}
                end
              end)
              |> elem(1)
              |> Enum.reverse()
            else
              for x <- part, do: EHLS.pack([apply(mod, fun, [x | levels])], out_layout)
            end
            |> IO.iodata_to_binary()

          input = EHLS.pack(part, in_layout)
          infile = Path.join(dir, "#{sig["kernel"]}_#{idx}.in")
          File.write!(infile, input)

          # the whole stream in one call, then in chunks: the state must be kept between calls
          for chunk <- [length(part), 1, 3, 7], reduce: errs do
            errs ->
              outfile = Path.join(dir, "#{sig["kernel"]}_#{idx}.out")
              case System.cmd(exe, [infile, outfile, to_string(chunk) | Enum.map(levels, &to_string/1)]) do
                {_, 0} -> :ok
                {_, code} -> raise "#{sig["kernel"]}: the test program exited with #{code} (chunk #{chunk}, half #{idx})"
              end

              got = File.read!(outfile)

              if got == expected do
                errs
              else
                at = Enum.find(0..(max(byte_size(got), byte_size(expected)) - 1)//1, fn i -> binary_part_safe(got, i) != binary_part_safe(expected, i) end)
                IO.puts("MISMATCH #{sig["kernel"]} (chunk #{chunk}, half #{idx}): byte #{at}: got #{inspect(binary_part_safe(got, at))}, expected #{inspect(binary_part_safe(expected, at))}; #{byte_size(got)} bytes, expected #{byte_size(expected)}")
                [{chunk, idx, at} | errs]
              end
          end
      end

    {length(xs), length(errors)}
  end

  defp binary_part_safe(b, i) when i < byte_size(b), do: :binary.at(b, i)
  defp binary_part_safe(_, _), do: nil

  # a flat list of values into the nested tuple a type name describes
  defp shape(t, [x | rest]) when is_binary(t), do: {x, rest}

  defp shape(l, values) when is_list(l) do
    {items, rest} = Enum.map_reduce(l, values, &shape/2)
    {if(length(items) == 1, do: hd(items), else: List.to_tuple(items)), rest}
  end
end
