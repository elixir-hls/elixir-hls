#!/usr/bin/env python3
"""Generate the memory space of a defhls kernel with tables / memories: `<kernel>_space`, the
module serving the kernel's external memory ports (CIRCT handshake: in<K>_ld<j> load ports,
in<K>_st<j> store ports) from its regions (lib/ehls/mlir.ex: ROM tables, RAM memories, each
at a multiple of its power-of-two size).

usage: gen_space.py <kernel>.sig <kernel>.sv <out.v>
Prints "K NLD NST": the memref argument index and the number of load / store ports.

Per region, one request per clock (lowest port first, stores before loads): a load's data
is the registered read (case ROM or RAM, so the FPGA tools can use block RAM) the clock after,
offered straight to the port and held in the port's register if not taken at once; a port
takes its next address in the clock its data is taken (one load outstanding, one per clock
at best). A store writes and then offers its done token. `restart` zero-fills the RAM
regions (requests wait).

The CPU reads a RAM region's word through `cpu_addr` / `cpu_req` (a pulse): first in its
region's next free clock (the kernel's requests wait that one clock), `cpu_q` the word and
`cpu_done` set the clock after the read, until the next request. An address in no RAM region
(a table, or past them) is done at once with 0.
"""
import json
import re
import sys

sig_path, sv_path, out_path = sys.argv[1:4]
sig = json.load(open(sig_path))
space = sig["space"]
top = sig["kernel"]
aw = space["aw"]
sv = open(sv_path).read()
ports = re.search(rf"module {top}\((.*?)\);", sv, re.S).group(1)
# the memref argument: after x (a frame of in_words), the state and the level arguments
k = sig.get("in_words", 1) + len(sig["state"]) + len(sig.get("args", []))
nld = len(set(re.findall(rf"\bin{k}_ld(\d+)_addr\b", ports)))
nst = len(set(re.findall(rf"\bin{k}_st(\d+)\b", ports)))

L = []
w = L.append
w(f"// Generated by elixir-hls priv/gen_space.py: the memory space of kernel {top}")
w(f"module {top}_space (")
w("    input  wire clk, input wire rst, input wire restart,")
plist = [f"input wire [{aw-1}:0] cpu_addr", "input wire cpu_req", "output reg [31:0] cpu_q", "output reg cpu_done"]
for j in range(nld):
    plist += [f"input wire [{aw-1}:0] ld{j}_addr", f"input wire ld{j}_addr_valid", f"output wire ld{j}_addr_ready",
              f"output wire [31:0] ld{j}_data", f"output wire ld{j}_data_valid", f"input wire ld{j}_data_ready"]
for j in range(nst):
    plist += [f"input wire [{aw+31}:0] st{j}", f"input wire st{j}_valid", f"output wire st{j}_ready",
              f"output reg st{j}_done_valid", f"input wire st{j}_done_ready"]
w(",\n".join("    " + p for p in plist))
w(");")
for j in range(nld):
    # busy: a load accepted and its data not taken yet; free: it is taken in this clock
    w(f"    reg ld{j}_busy; reg ld{j}_held; reg [31:0] ld{j}_hq; wire ld{j}_free;")
# the CPU's read: pending from its request until a region takes it
w("    reg cpu_pend;")
cpu_grants = []

grants_ld = {j: [] for j in range(nld)}
grants_st = {j: [] for j in range(nst)}
for ri, r in enumerate(space["regions"]):
    rw = max(1, (r["size"] - 1).bit_length())
    base, size = r["base"], r["size"]
    hi = aw - 1
    # the region: address bits above rw equal base's
    def inside(sig_name, off=0):
        """the address (bits off .. off+aw-1 of sig_name) is in this region"""
        if rw >= aw:
            return "1'b1"
        return f"({sig_name}[{hi + off}:{rw + off}] == {aw - rw}'d{base >> rw})"
    w(f"    // region {ri}: {r['kind']} {r['name']}, {size} words at {base}")
    w(f"    reg [{rw-1}:0] r{ri}_a; reg r{ri}_rv; reg [7:0] r{ri}_port; reg [31:0] r{ri}_q;")
    dw = r.get("width", 32)
    if r["kind"] == "ram":
        # one write port (a store or the zero-fill) and one registered read: block RAM, even
        # when small (the GW5A has no distributed RAM; registers would cost far more), as
        # wide as the memory's element
        w(f"    (* syn_ramstyle = \"block_ram\" *) reg [{dw-1}:0] r{ri}_mem [0:{(1 << rw) - 1}];")
        w(f"    reg r{ri}_clr; reg [{rw-1}:0] r{ri}_cp;")
        w("`ifdef __ICARUS__")
        w(f"    integer r{ri}_i; initial for (r{ri}_i = 0; r{ri}_i < {1 << rw}; r{ri}_i = r{ri}_i + 1) r{ri}_mem[r{ri}_i] = 0;")
        w("`endif")
    # requests
    st_req = [f"(st{j}_valid && !st{j}_done_valid && {inside(f'st{j}', 32)})" for j in range(nst)] if r["kind"] == "ram" else []
    ld_req = [f"(ld{j}_addr_valid && ld{j}_free && {inside(f'ld{j}_addr')})" for j in range(nld)]
    free = f"!r{ri}_clr" if r["kind"] == "ram" else "1'b1"
    # priority chain: the CPU's read, stores, then loads
    chain = []
    if r["kind"] == "ram":
        w(f"    wire r{ri}_gc = {free} && cpu_pend && {inside('cpu_addr')};")
        w(f"    reg r{ri}_cv;")
        chain.append(f"r{ri}_gc")
        cpu_grants.append(ri)
    for j, q in enumerate(st_req):
        g = f"r{ri}_gst{j}"
        w(f"    wire {g} = {free} && {q}" + "".join(f" && !{c}" for c in chain) + ";")
        chain.append(g)
        grants_st[j].append(g)
    for j, q in enumerate(ld_req):
        g = f"r{ri}_gld{j}"
        w(f"    wire {g} = {free} && {q}" + "".join(f" && !{c}" for c in chain) + ";")
        chain.append(g)
        grants_ld[j].append(g)
    gaddr = " : ".join(([f"r{ri}_gc ? cpu_addr[{rw-1}:0]"] if r["kind"] == "ram" else []) +
                       [f"{g} ? ld{j}_addr[{rw-1}:0]" for j, g in [(int(c.split('gld')[1]), c) for c in chain if 'gld' in c]] + ["'0"])
    w(f"    wire [{rw-1}:0] r{ri}_ga = {gaddr};")
    w(f"    wire r{ri}_gl = {' || '.join(c for c in chain if 'gld' in c) or '1\'b0'};")
    w(f"    wire [7:0] r{ri}_gp = " + " : ".join([f"{c} ? 8'd{c.split('gld')[1]}" for c in chain if 'gld' in c] + ["8'd0"]) + ";")
    if r["kind"] == "ram":
        gs = [f"r{ri}_gst{j}" for j in range(nst)]
        wa = " : ".join([f"{g} ? st{j}[{rw+31}:32]" for j, g in enumerate(gs)] + [f"r{ri}_cp"])
        wd = " : ".join([f"{g} ? st{j}[{dw-1}:0]" for j, g in enumerate(gs)] + [f"{dw}'d0"])
        w(f"    wire r{ri}_we = r{ri}_clr" + "".join(f" || {g}" for g in gs) + ";")
        w(f"    wire [{rw-1}:0] r{ri}_wa = {wa};")
        w(f"    wire [{dw-1}:0] r{ri}_wd = {wd};")
    w("    always @(posedge clk) begin")
    if r["kind"] == "rom":
        w(f"        case (r{ri}_ga)")
        for i, v in enumerate(r["values"]):
            w(f"            {rw}'d{i}: r{ri}_q <= 32'h{v:08x};")
        w("            default: r{0}_q <= 32'h0;".format(ri))
        w("        endcase")
    else:
        w(f"        r{ri}_q <= {{{32 - dw}'d0, r{ri}_mem[r{ri}_ga]}};" if dw < 32 else f"        r{ri}_q <= r{ri}_mem[r{ri}_ga];")
        w(f"        if (r{ri}_we) r{ri}_mem[r{ri}_wa] <= r{ri}_wd;")
        w(f"        if (r{ri}_clr) begin r{ri}_cp <= r{ri}_cp + 1'b1;")
        w(f"            if (r{ri}_cp == {rw}'d{(1 << rw) - 1}) r{ri}_clr <= 1'b0; end")
        w(f"        if (rst) begin r{ri}_clr <= 1'b0; r{ri}_cp <= 0; end")
        w(f"        else if (restart) begin r{ri}_clr <= 1'b1; r{ri}_cp <= 0; end")
    w(f"        r{ri}_rv <= r{ri}_gl && !rst;")
    if r["kind"] == "ram":
        w(f"        r{ri}_cv <= r{ri}_gc && !rst;")
    w(f"        r{ri}_port <= r{ri}_gp;")
    w("    end")

# ports: address / store acceptance, data (fresh from a region or held), done registers
for j in range(nld):
    gs = grants_ld[j]
    fresh = " || ".join(f"(r{ri}_rv && r{ri}_port == 8'd{j})" for ri in range(len(space["regions"]))) or "1'b0"
    freshq = " : ".join(f"(r{ri}_rv && r{ri}_port == 8'd{j}) ? r{ri}_q" for ri in range(len(space["regions"]))) + " : 32'h0"
    w(f"    wire ld{j}_fresh = {fresh};")
    w(f"    assign ld{j}_data_valid = ld{j}_held || ld{j}_fresh;")
    w(f"    assign ld{j}_data = ld{j}_held ? ld{j}_hq : ({freshq});")
    w(f"    assign ld{j}_free = !ld{j}_busy || (ld{j}_data_valid && ld{j}_data_ready);")
    w(f"    assign ld{j}_addr_ready = {' || '.join(gs) or '1\'b0'};")
for j in range(nst):
    gs = grants_st[j]
    w(f"    assign st{j}_ready = {' || '.join(gs) or '1\'b0'};")
# the CPU's read: the word the clock after its region took it
w("    always @(posedge clk) begin")
w("        if (rst) begin cpu_pend <= 1'b0; cpu_done <= 1'b0; end")
w("        else if (cpu_req) begin cpu_pend <= 1'b1; cpu_done <= 1'b0; end")
taken = " || ".join(f"r{ri}_gc" for ri in cpu_grants) or "1'b0"
w(f"        else if ({taken}) cpu_pend <= 1'b0;")
# in no RAM region: done with 0 (so that a read never waits forever)
rams = [ri for ri, r in enumerate(space["regions"]) if r["kind"] == "ram"]
def inside_ram(ri):
    r = space["regions"][ri]
    rw = max(1, (r["size"] - 1).bit_length())
    return "1'b1" if rw >= aw else f"(cpu_addr[{aw - 1}:{rw}] == {aw - rw}'d{r['base'] >> rw})"
anywhere = " || ".join(inside_ram(ri) for ri in rams) or "1'b0"
w(f"        else if (cpu_pend && !({anywhere})) begin cpu_pend <= 1'b0; cpu_q <= 32'h0; cpu_done <= 1'b1; end")
for ri in cpu_grants:
    w(f"        else if (r{ri}_cv) begin cpu_q <= r{ri}_q; cpu_done <= 1'b1; end")
w("    end")
w("    always @(posedge clk) begin")
w("        if (rst) begin")
for j in range(nld):
    w(f"            ld{j}_busy <= 1'b0; ld{j}_held <= 1'b0;")
for j in range(nst):
    w(f"            st{j}_done_valid <= 1'b0;")
w("        end else begin")
for j in range(nld):
    w(f"            if (ld{j}_data_valid && ld{j}_data_ready) begin ld{j}_busy <= 1'b0; ld{j}_held <= 1'b0; end")
    w(f"            else if (ld{j}_fresh) begin ld{j}_held <= 1'b1; ld{j}_hq <= ld{j}_data; end")
    w(f"            if (ld{j}_addr_valid && ld{j}_addr_ready) ld{j}_busy <= 1'b1;")
for j in range(nst):
    w(f"            if (st{j}_valid && st{j}_ready) st{j}_done_valid <= 1'b1;")
    w(f"            else if (st{j}_done_valid && st{j}_done_ready) st{j}_done_valid <= 1'b0;")
w("        end")
w("    end")
w("endmodule")
open(out_path, "w").write("\n".join(L) + "\n")
print(k, nld, nst)
