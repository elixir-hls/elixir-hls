#!/usr/bin/env python3
"""Write the C headers of the NIFs from the SoC's csr.json:
  <out_dir>/hwstream_csr.h : hwstream_* CSRs (instances, CPU ends) as HWSTREAM_*, and the ends as a
      table (HWSTREAM_ENDS: base, length, enable, finished of end i)
  <out_dir>/ehls_regs.h : the addresses of the packages' registers, by their numbers (the
      LiteX CSR <gateware>_<name>, from packages.json next to the application's kernels:
      <out_dir>/../hw); empty without any
  and, for the block packages (their roots as arguments), the headers their
  csr_headers.json asks for:
      {"usbh_csr.h": "usbh_", "lcd_csr.h": "lcd_"}
  (this backend's own csr_headers.json too) each with CSR_<NAME>_ADDR for the CSRs starting with
  the prefix, CSR_<NAME>_INTERRUPT for the interrupts, MEM_<NAME>_BASE for the memory regions
  starting with it, CSR_SYS_CLK_FREQ, CSR_CPU_HAS_DCACHE (when the CPU has
  one) and MEM_MAIN_RAM_BASE. A header whose prefix matches no CSR is not written (and an old
  one removed): the package's C sources test for it with __has_include, so a NIF is only built
  into AtomVM when the SoC has its peripheral.
usage: gen_csr_header.py <csr.json> <out_dir> [package root]...
"""
import json
import os
import sys

csr = json.load(open(sys.argv[1]))
out = sys.argv[2]
packages = [os.path.dirname(os.path.abspath(__file__))] + sys.argv[3:]
regs = csr["csr_registers"]
main_ram = csr["memories"]["main_ram"]["base"]

with open(os.path.join(out, "hwstream_csr.h"), "w") as f:
    f.write("/* Generated by elixir-hls gen_csr_header.py from csr.json */\n#pragma once\n")
    f.write(f"#define HWSTREAM_MAIN_RAM_BASE 0x{main_ram:08x}u\n")
    for name, r in sorted(regs.items()):
        if name.startswith("hwstream_"):
            f.write(f"#define {name.upper()} 0x{r['addr']:08x}u\n")
    f.write(f"#define HWSTREAM_MAIN_RAM_SIZE 0x{csr['memories']['main_ram']['size']:08x}u\n")
    # the system clock: event times are its cycles
    f.write(f"#define HWSTREAM_SYS_CLK_FREQ {csr['constants']['config_clock_frequency']}u\n")
    if "hwstream_interrupt" in csr["constants"]:
        f.write(f"#define HWSTREAM_INTERRUPT {csr['constants']['hwstream_interrupt']}\n")
    n = 0
    while f"hwstream_end{n}_base" in regs:
        n += 1
    f.write(f"#define HWSTREAM_ENDS_COUNT {n}\n#define HWSTREAM_ENDS {{ \\\n")
    for i in range(n):
        addrs = ", ".join(f"0x{regs[f'hwstream_end{i}_{r}']['addr']:08x}u" for r in ("base", "length", "enable", "finished"))
        f.write(f"    {{ {addrs} }}, \\\n")
    f.write("}\n")

# the packages' registers by number (gen_manifest.py), checked against the SoC
pj = os.path.join(out, "..", "hw", "packages.json")
addrs = {}
for p in json.load(open(pj)) if os.path.exists(pj) else []:
    for r in p.get("registers", []):
        name = f"{p['gateware']}_{r['name']}"
        if name not in regs:
            sys.exit(f"gen_csr_header: no CSR {name} in {sys.argv[1]}: an old SoC?")
        addrs[r["index"]] = (name, regs[name]["addr"])
with open(os.path.join(out, "ehls_regs.h"), "w") as f:
    f.write("/* Generated by elixir-hls gen_csr_header.py from csr.json and packages.json */\n#pragma once\n")
    f.write(f"#define EHLS_REGS_COUNT {len(addrs)}\n")
    f.write("#define EHLS_REGS { \\\n")
    for i in sorted(addrs):
        f.write(f"    0x{addrs[i][1]:08x}u, /* {i}: {addrs[i][0]} */ \\\n")
    f.write("}\n")

for pkg in packages:
    spec = os.path.join(pkg, "csr_headers.json")
    if not os.path.exists(spec):
        continue
    for header, prefix in json.load(open(spec)).items():
        path = os.path.join(out, header)
        names = sorted(n for n in regs if n.startswith(prefix))
        if not names:
            if os.path.exists(path):
                os.remove(path)
            continue
        lines = ["/* Generated by elixir-hls gen_csr_header.py from csr.json */", "#pragma once"]
        for n in names:
            lines.append(f"#define CSR_{n.upper()}_ADDR 0x{regs[n]['addr']:08x}u")
        for n, m in sorted(csr.get("memories", {}).items()):
            if n.startswith(prefix):
                lines.append(f"#define MEM_{n.upper()}_BASE 0x{m['base']:08x}u")
        for n, v in sorted(csr["constants"].items()):
            if n.endswith("_interrupt") and n.startswith(prefix):
                lines.append(f"#define CSR_{n.upper()} {v}")
        lines.append(f"#define CSR_SYS_CLK_FREQ {csr['constants']['config_clock_frequency']}u")
        if "config_cpu_has_dcache" in csr["constants"]:
            lines.append("#define CSR_CPU_HAS_DCACHE 1")
        lines.append(f"#define MEM_MAIN_RAM_BASE 0x{main_ram:08x}u")
        open(path, "w").write("\n".join(lines) + "\n")
