#!/usr/bin/env python3
"""The AtomVM runtime backend's index module: the Erlang module hw_kernels (pipeline / end /
state / level indices for the generated calls to hwstream) from build/hw's
kernels.json and pipelines.json (priv/gen_manifest.py numbers them).

usage: gen_hw_kernels.py <build/hw> <hw_kernels.erl>
"""
import json
import os
import sys

hw, erl = sys.argv[1:3]
kernels = json.load(open(os.path.join(hw, "kernels.json")))
pipelines = json.load(open(os.path.join(hw, "pipelines.json")))
by_name = {k["kernel"]: k for k in kernels}
packages_json = os.path.join(hw, "packages.json")
packages = json.load(open(packages_json)) if os.path.exists(packages_json) else []


def term(v):
    """A table entry (JSON) as an Erlang term: a list is a tuple, a string an atom."""
    if isinstance(v, list):
        return "{" + ", ".join(term(x) for x in v) + "}"
    return f"'{v}'" if isinstance(v, str) else str(v)


with open(erl, "w") as f:
    f.write("%% Generated by elixir-hls priv/backend/atomvm/gen_hw_kernels.py: indices of the defhls kernels and pipelines.\n")
    f.write("-module(hw_kernels).\n-export([pipeline/1, cpu_end/2, cpu_ends/1, state/2, hold/2, level/1, topic/1, runtime/0, reg/2, data/2]).\n\n")
    for p in pipelines:
        f.write(f"pipeline('{p['module']}.{p['name']}') -> {p['index']};\n")
    f.write("pipeline(Pipeline) -> erlang:error({no_hw_pipeline, Pipeline}).\n\n")
    # cpu_end(Pipeline, Name): the index of its input or output (out)
    for p in pipelines:
        for e in p["ends"]:
            f.write(f"cpu_end('{p['module']}.{p['name']}', '{e['name']}') -> {e['index']};\n")
    f.write("cpu_end(Pipeline, Name) -> erlang:error({no_cpu_end, Pipeline, Name}).\n\n")
    # cpu_ends(Pipeline): the indices of all its CPU ends (not those wired to another instance)
    for p in pipelines:
        f.write(f"cpu_ends('{p['module']}.{p['name']}') -> {[e['index'] for e in p['ends']]};\n")
    f.write("cpu_ends(_Pipeline) -> [].\n\n")
    # state(Pipeline, Name): the index of its stage transform(.., name: Name) and the state words' types
    for p in pipelines:
        for st in p["stages"]:
            if "peek" in st and "kernel" in st:
                k = by_name[st["kernel"]]
                types = ", ".join("{%d, %s}" % (int(t[1:]), "true" if t[0] == "s" else "false") for t in k["state"])
                if "shape" in k:
                    # a state holding memories: its parts, a value's zeros or a memory's address, size and type
                    regions = {r["name"]: r for r in k["space"]["regions"]}
                    elems = {m["name"]: m["elem"] for m in k["memories"]}
                    def erl_term(z):
                        return "{" + ", ".join(erl_term(v) for v in z) + "}" if isinstance(z, list) else str(z)
                    def part(pt):
                        if "mem" in pt:
                            m = "hw__m_" + pt["mem"]
                            e = elems[m]
                            return "{mem, %d, %d, {%d, %s}}" % (regions[m]["base"], pt["n"], int(e[1:]), "true" if e[0] == "s" else "false")
                        return "{val, %s}" % erl_term(pt["val"])
                    parts = ", ".join(part(pt) for pt in k["shape"])
                    if not any("val" in pt for pt in k["shape"]):
                        types = ""      # the whole state a memory: the kernel's one state word is no part of it
                    f.write(f"state('{p['module']}.{p['name']}', '{st['state_name']}') -> {{{st['peek']}, [{types}], [{parts}]}};\n")
                else:
                    f.write(f"state('{p['module']}.{p['name']}', '{st['state_name']}') -> {{{st['peek']}, [{types}]}};\n")
    f.write("state(Pipeline, Stage) -> erlang:error({no_named_state, Pipeline, Stage}).\n")
    # hold(Pipeline, Name): the index of its hold(Name) stage and the word's type
    for p in pipelines:
        for st in p["stages"]:
            if st.get("block") == "hold":
                t = st["hold_type"]
                f.write(f"hold('{p['module']}.{p['name']}', '{st['args'][0]}') -> {{{st['peek']}, [{{{int(t[1:])}, {'true' if t[0] == 's' else 'false'}}}]}};\n")
    f.write("hold(Pipeline, Name) -> erlang:error({no_hold_stage, Pipeline, Name}).\n\n")
    # level(Pipeline): an instance of levels' number for its writes and for reading its count and result
    for p in pipelines:
        if "level" in p:
            f.write(f"level('{p['module']}.{p['name']}') -> {{{p['level']['index']}, {p['level']['peek']}}};\n")
    f.write("level(Pipeline) -> erlang:error({no_level_instance, Pipeline}).\n\n")
    # topic(Name): an event topic's number and its values' {bits, signed} (EHLS.PubSub.subscribe)
    tj = os.path.join(hw, "topics.json")
    for t in json.load(open(tj)) if os.path.exists(tj) else []:
        f.write(f"topic('{t['name']}') -> {{{t['id']}, {int(t['type'][1:])}, {'true' if t['type'][0] == 's' else 'false'}}};\n")
    f.write("topic(Topic) -> erlang:error({no_topic, Topic}).\n\n")
    # the runtime module, for code compiled without knowing it (EHLS.GPIO)
    f.write("\nruntime() -> hwstream.\n\n")
    # reg(Gateware, Name): a package's register number; data(Gateware, Key): its table
    for p in packages:
        for r in p.get("registers", []):
            f.write(f"reg('{p['gateware']}', '{r['name']}') -> {r['index']};\n")
    f.write("reg(Package, Name) -> erlang:error({no_register, Package, Name}).\n\n")
    for p in packages:
        for k, v in p.get("table", {}).items():
            f.write(f"data('{p['gateware']}', '{k}') -> {term(v)};\n")
    f.write("data(_Package, _Key) -> undefined.\n")
